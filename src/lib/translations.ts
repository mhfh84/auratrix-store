export type Translations = typeof translations.en;

/**
 * Safely extracts localized string if user configured pipe-separated 'Arabic | English' text,
 * or returns raw text if single language.
 */
export function getLocalizedText(
  text: string | undefined | null,
  language: "ar" | "en" = "ar",
): string {
  if (!text) return "";
  if (text.includes("|")) {
    const parts = text.split("|").map((s) => s.trim());
    if (language === "ar") {
      return parts[0] || "";
    } else {
      return parts[1] || parts[0] || "";
    }
  }
  return text;
}

/**
 * Returns formatted store name or fallback.
 */
export function getStoreName(
  storeName: string | undefined | null,
  fallback = "Store",
): string {
  if (!storeName || !storeName.trim()) return fallback;
  return storeName.trim();
}
